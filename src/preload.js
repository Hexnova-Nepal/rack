'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);
const on = (ch) => (cb) => {
  const f = (_e, d) => cb(d);
  ipcRenderer.on(ch, f);
  return () => ipcRenderer.removeListener(ch, f);
};

